create table if not exists public.cad_setor_comercial_lista (
  nome text primary key,
  ordem int not null default 100,
  mercadoria boolean not null default true  -- false: serviço/taxa (entra no faturamento, mas não é mercadoria)
);
alter table public.cad_setor_comercial_lista enable row level security;

create table if not exists public.cad_setor_comercial (
  idmercadoriavariacao bigint primary key,
  setor text not null references public.cad_setor_comercial_lista (nome) on update cascade,
  origem text not null default 'planilha',
  atualizado_em timestamptz not null default now(),
  atualizado_por text
);
alter table public.cad_setor_comercial enable row level security;
create index if not exists cad_setor_comercial_setor on public.cad_setor_comercial (setor);

create table if not exists public.ref_relatorio_erp (
  mes date primary key,
  inicio timestamptz not null,
  fim timestamptz not null,
  faturamento numeric not null,
  quantidade numeric not null,
  lucro numeric not null,
  arquivo text,
  fonte text not null default 'Relatório "Lucro bruto das mercadorias vendidas no período e desconto" do ERP'
);
alter table public.ref_relatorio_erp enable row level security;

