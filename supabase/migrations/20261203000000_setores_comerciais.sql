  base text; onde text := 'true'; sel text := ''; grp text := ''; tot text := ''; ord text; g text; m text;
  grupos text[] := array(select jsonb_array_elements_text(coalesce(p->'grupos', '[]'::jsonb)));
  metricas text[] := array(select jsonb_array_elements_text(coalesce(p->'metricas', '["liquido"]'::jsonb)));
  dims jsonb := jsonb_build_object(
    'dia',        jsonb_build_array('b.data', 'b.data as dia'),
    'semana',     jsonb_build_array('date_trunc(''week'', b.data)::date', 'date_trunc(''week'', b.data)::date as semana'),
    'mes',        jsonb_build_array('to_char(b.data, ''YYYY-MM'')', 'to_char(b.data, ''YYYY-MM'') as mes'),
    'ano',        jsonb_build_array('extract(year from b.data)::int', 'extract(year from b.data)::int as ano'),
    'empresa',    jsonb_build_array('b.idempresa', 'b.idempresa as empresa'),
    'item',       jsonb_build_array('b.idmercadoriavariacao', 'b.idmercadoriavariacao as variacao, b.idmercadoriavariacao as codigo, max(b.item) as produto'),
    'setor',      jsonb_build_array('coalesce(b.setor, ''Não classificado'')', 'coalesce(b.setor, ''Não classificado'') as setor'),
    'setor_comercial', jsonb_build_array('b.setor_comercial', 'b.setor_comercial as setor_comercial'),
    'secao',      jsonb_build_array('coalesce(b.secao, ''Sem seção'')', 'coalesce(b.secao, ''Sem seção'') as secao'),
    'vendedora',  jsonb_build_array('b.vendedora_id', 'b.vendedora_id as codigo_vendedora, coalesce(max(b.vendedora), ''Sem vendedora'') as vendedora'),
    'cliente',    jsonb_build_array('b.cliente_id', 'b.cliente_id as codigo_cliente, coalesce(max(b.cliente), ''Sem cliente'') as cliente'),
    'fornecedor', jsonb_build_array('b.fornecedor_id', 'b.fornecedor_id as codigo_fornecedor, coalesce(max(b.fornecedor), ''Sem fornecedor'') as fornecedor'),
    'documento',  jsonb_build_array('b.documento', 'b.documento as documento, min(b.data) as data_documento'),
    'faixa',      jsonb_build_array('b.faixa', 'b.faixa as faixa'),
    'lote',       jsonb_build_array('b.idmercadoriavariacao, b.lote, b.data', 'b.idmercadoriavariacao as variacao, b.idmercadoriavariacao as codigo, max(b.item) as produto, b.lote as lote, b.data as validade'));
  mets jsonb := jsonb_build_object(
    'qtd',        'sum(b.qtd)',
    'bruto',      'sum(b.bruto)',
    'desconto',   'sum(b.desconto)',
    'liquido',    'sum(b.liquido)',
    'custo',      'sum(b.custo)',
    'lucro',      'sum(b.lucro)',
    'margem',     'round(sum(b.lucro) * 100 / nullif(sum(b.liquido), 0), 2)',
    'documentos', 'count(distinct b.documento)',
    'itens',      'count(*)',
    'ticket',     'round(sum(b.liquido) / nullif(count(distinct b.documento), 0), 2)',
    'clientes',   'count(distinct b.cliente_id)',
    'produtos',   'count(distinct b.idmercadoriavariacao)');
  nome_pessoa constant text := 'nullif(trim(concat_ws('' '', %1$s.nome, %1$s.sobrenome)), '''')';
  resultado jsonb; totais jsonb; n bigint;
begin
  if array_length(grupos, 1) > 3 then raise exception 'Escolha no máximo 3 agrupamentos.'; end if;
  if coalesce(array_length(metricas, 1), 0) = 0 then raise exception 'Escolha pelo menos uma métrica.'; end if;

  base := case fonte
    when 'vendas' then format($q$
      select v.data, v.idempresa, v.idmercadoriavariacao, n.idmercadoria, n.nome as item, c.setor, sc.descricao as secao, coalesce(scc.setor, 'Sem setor') as setor_comercial,
             v.idpessoafuncionario as vendedora_id, %s as vendedora, v.idcliente as cliente_id, %s as cliente,
             null::bigint as fornecedor_id, null::text as fornecedor, v.iddocumento as documento, null::text as lote, null::text as faixa,
             v.qtd, v.valtotalbruto as bruto, v.valdesconto as desconto, v.valtotalliquido as liquido, v.custo_total as custo, v.lucro_bruto as lucro
        from public.vw_venda_item v
        left join public.vw_variacao_nome n on n.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.vw_produto_classe c on c.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.erp_mercadoria_secao sc on sc._idsecao = v.idsecao
        left join public.erp_pessoa pf on pf._idpessoa = v.idpessoafuncionario
        left join public.erp_pessoa pc on pc._idpessoa = v.idcliente
       where v.data between $1 and $2$q$, format(nome_pessoa, 'pf'), format(nome_pessoa, 'pc'))
    when 'devolucoes' then format($q$
      select v.data, v.idempresa, v.idmercadoriavariacao, n.idmercadoria, n.nome as item, c.setor, sc.descricao as secao, coalesce(scc.setor, 'Sem setor') as setor_comercial,
             v.idpessoafuncionario as vendedora_id, %s as vendedora, v.idcliente as cliente_id, %s as cliente,
             null::bigint as fornecedor_id, null::text as fornecedor, v.iddocumento as documento, null::text as lote, null::text as faixa,
             v.qtd, null::numeric as bruto, null::numeric as desconto, v.valtotalliquido as liquido, null::numeric as custo, null::numeric as lucro
        from public.vw_devolucao_item v
        left join public.vw_variacao_nome n on n.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.vw_produto_classe c on c.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.erp_mercadoria m on m._idmercadoria = n.idmercadoria
        left join public.erp_mercadoria_secao sc on sc._idsecao = m.idsecao
        left join public.erp_pessoa pf on pf._idpessoa = v.idpessoafuncionario
        left join public.erp_pessoa pc on pc._idpessoa = v.idcliente
       where v.data between $1 and $2$q$, format(nome_pessoa, 'pf'), format(nome_pessoa, 'pc'))
    when 'compras' then format($q$
      select v.data, v.idempresa, v.idmercadoriavariacao, v.idmercadoria, coalesce(n.nome, v.descricao) as item, c.setor, sc.descricao as secao, coalesce(scc.setor, 'Sem setor') as setor_comercial,
             null::bigint as vendedora_id, null::text as vendedora, null::bigint as cliente_id, null::text as cliente,
             v.idfornecedor as fornecedor_id, %s as fornecedor, v.iddocumento as documento, v.lote, null::text as faixa,
             coalesce(v.qtdestoque, v.qtd) as qtd, null::numeric as bruto, null::numeric as desconto, v.valtotalliquido as liquido,
             v.valtotalliquido as custo, null::numeric as lucro
        from public.vw_compra_item v
        left join public.vw_variacao_nome n on n.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.vw_produto_classe c on c.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.erp_mercadoria m on m._idmercadoria = v.idmercadoria
        left join public.erp_mercadoria_secao sc on sc._idsecao = m.idsecao
        left join public.erp_pessoa pf on pf._idpessoa = v.idfornecedor
       where v.data between $1 and $2$q$, format(nome_pessoa, 'pf'))
    when 'estoque' then $q$
      select null::date as data, null::bigint as idempresa, v.idmercadoriavariacao, v.idmercadoria, v.descricao as item, v.setor, v.secao, coalesce(scc.setor, 'Sem setor') as setor_comercial,
             null::bigint as vendedora_id, null::text as vendedora, null::bigint as cliente_id, null::text as cliente,
             null::bigint as fornecedor_id, null::text as fornecedor, null::bigint as documento, null::text as lote, v.situacao as faixa,
             v.estoque_atual as qtd, null::numeric as bruto, null::numeric as desconto, null::numeric as liquido, v.valor_estoque as custo, null::numeric as lucro
        from public.vw_produto_ncm v
        left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = v.idmercadoriavariacao
       where v.estoque_atual <> 0 and $1 is not null and $2 is not null$q$
    when 'validades' then $q$
      select v.dtvalidade as data, v.idempresa, v.idmercadoriavariacao, n.idmercadoria, v.descricao as item, c.setor, null::text as secao, coalesce(scc.setor, 'Sem setor') as setor_comercial,
             null::bigint as vendedora_id, null::text as vendedora, null::bigint as cliente_id, null::text as cliente,
             null::bigint as fornecedor_id, null::text as fornecedor, null::bigint as documento, v.lote, v.faixa,
             v.qtdsaldo as qtd, null::numeric as bruto, null::numeric as desconto, null::numeric as liquido, v.valor_em_risco as custo, null::numeric as lucro
        from public.vw_lote_disponivel v
        left join public.vw_variacao_nome n on n.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.vw_produto_classe c on c.idmercadoriavariacao = v.idmercadoriavariacao
        left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = v.idmercadoriavariacao
       where v.dtvalidade between $1 and $2$q$
    else null end;
  if base is null then raise exception 'Fonte de dados inválida: %', fonte; end if;

  -- Filtros (valores como parâmetro $3).
  if f ? 'empresa'    then onde := onde || ' and b.idempresa = ($3->>''empresa'')::bigint'; end if;
  if f ? 'vendedora'  then onde := onde || ' and coalesce(b.vendedora_id, 0) = ($3->>''vendedora'')::bigint'; end if;
  if f ? 'cliente'    then onde := onde || ' and b.cliente_id = ($3->>''cliente'')::bigint'; end if;
  if f ? 'fornecedor' then onde := onde || ' and b.fornecedor_id = ($3->>''fornecedor'')::bigint'; end if;
  if f ? 'setor'      then onde := onde || ' and coalesce(b.setor, ''Não classificado'') = ($3->>''setor'')'; end if;
  if f ? 'setor_comercial' then onde := onde || ' and b.setor_comercial = ($3->>''setor_comercial'')'; end if;
  if f ? 'secao'      then onde := onde || ' and b.secao ilike ''%'' || ($3->>''secao'') || ''%'''; end if;
  if f ? 'faixa'      then onde := onde || ' and b.faixa = ($3->>''faixa'')'; end if;
  if f ? 'produto' then
    onde := onde || case when (f->>'produto') ~ '^\d{1,9}$'
      then ' and (b.idmercadoria = ($3->>''produto'')::bigint or b.idmercadoriavariacao = ($3->>''produto'')::bigint)'
      else ' and b.item ilike ''%'' || replace($3->>''produto'', '' '', ''%'') || ''%''' end;
  end if;

  foreach g in array grupos loop
    if not dims ? g then raise exception 'Agrupamento inválido: %', g; end if;
    sel := sel || (dims->g->>1) || ', ';
    grp := grp || (case when grp = '' then '' else ', ' end) || (dims->g->>0);
  end loop;
  foreach m in array metricas loop
    if not mets ? m then raise exception 'Métrica inválida: %', m; end if;
    sel := sel || (mets->>m) || ' as ' || m || ', ';
    tot := tot || (mets->>m) || ' as ' || m || ', ';
  end loop;
  sel := left(sel, length(sel) - 2); tot := left(tot, length(tot) - 2);
  -- Validades: cada linha traz a validade mais próxima, e a ordem padrão é por ela.
  if fonte = 'validades' and array_length(grupos, 1) > 0 then sel := sel || ', min(b.data) as proxima_validade'; end if;

  ord := coalesce(p->>'ordem', '');
  if not (ord = any(metricas) or (ord = any(grupos) and ord not in ('item', 'vendedora', 'cliente', 'fornecedor', 'documento', 'lote'))) then
    ord := case when array_length(grupos, 1) > 0 and grupos[1] in ('dia', 'semana', 'mes', 'ano') then grupos[1] else metricas[1] end;
  end if;
  if ord = any(grupos) and ord not in ('dia', 'semana', 'mes', 'ano', 'empresa', 'setor', 'setor_comercial', 'secao', 'faixa') then ord := metricas[1]; end if;
  if fonte = 'validades' and array_length(grupos, 1) > 0 then
    -- O que vence primeiro no topo, vencidos juntos no fim; ordenando por um valor, a validade desempata.
    if coalesce(p->>'ordem', '') in ('', 'validade') or not (p->>'ordem' = any(metricas) or p->>'ordem' = any(grupos)) then
      ord := '(proxima_validade < (now() at time zone ''America/Belem'')::date) ' || case when lower(coalesce(p->>'dir', 'asc')) = 'desc' then 'desc' else 'asc' end
          || ', proxima_validade ' || case when lower(coalesce(p->>'dir', 'asc')) = 'desc' then 'desc' else 'asc' end || ' nulls last';
    else
      ord := ord || case when lower(coalesce(p->>'dir', '')) = 'asc' then ' asc' else ' desc' end || ' nulls last, proxima_validade asc nulls last';
    end if;
  else
    ord := ord || case when lower(coalesce(p->>'dir', '')) = 'asc' or (p->>'dir' is null and ord in ('dia', 'semana', 'mes', 'ano')) then ' asc' else ' desc' end || ' nulls last';
  end if;

  execute format('select jsonb_build_object(%s) from (%s) b where %s',
                 (select string_agg(format('%L, %s', x, mets->>x), ', ') from unnest(metricas) x), base, onde)
    into totais using de, ate, f;

  if array_length(grupos, 1) > 0 then
    execute format('select count(*) from (select 1 from (%s) b where %s group by %s) q', base, onde, grp) into n using de, ate, f;
    execute format('select coalesce(jsonb_agg(to_jsonb(r) - ''_ordem'' order by r._ordem), ''[]''::jsonb) from (select row_number() over (order by %s) as _ordem, x.* from (select %s from (%s) b where %s group by %s) x order by %s limit %s) r',
                   ord, sel, base, onde, grp, ord, limite) into resultado using de, ate, f;
  else
    n := 1; resultado := jsonb_build_array(totais);
  end if;
  return jsonb_build_object('linhas', resultado, 'totais', totais, 'total_linhas', n, 'limitado', n > limite);
end $$;


-- Perda por volume: em cada setor comercial, o mês completo de maior quantidade vendida é a referência (pico).
-- Para cada produto, a diferença de unidades contra o pico vira dinheiro pelo preço líquido unitário do pico
-- (ou do próprio mês, se o produto não vendeu no pico). Perda bruta = unidades a menos; ganho = unidades a mais;
-- impacto líquido = ganho - perda; efeito preço/mix = variação real do faturamento - impacto líquido.
-- Mesmo método da aba "Perda por volume" da planilha (confere ao centavo com Rações: Out/26 x Mai/26).
-- p: {"mes": "2026-10-01" (mês analisado; padrão: último mês completo), "setor": "Rações / Alimentação"}
create or replace function public.perda_volume(p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, pg_catalog as $$
declare
  hoje date := (now() at time zone 'America/Belem')::date;
  limite_mes date := date_trunc('month', hoje)::date;          -- mês em andamento não entra
  alvo date := date_trunc('month', coalesce(nullif(p->>'mes', '')::date, (limite_mes - interval '1 month')::date))::date;
  ini date; sel text := nullif(p->>'setor', ''); res jsonb;
begin
  if alvo >= limite_mes then alvo := (limite_mes - interval '1 month')::date; end if;
  ini := date_trunc('year', alvo)::date;

  with _pv_base as materialized (
    select coalesce(s.setor, 'Sem setor') as setor, v.idmercadoriavariacao as id, date_trunc('month', v.data)::date as mes, sum(v.qtd) as qtd, sum(v.valtotalliquido) as fat
      from public.vw_venda_item v left join public.cad_setor_comercial s on s.idmercadoriavariacao = v.idmercadoriavariacao
     where v.data >= ini and v.data < (alvo + interval '1 month')::date
     group by 1, 2, 3),
  setor_mes as (select setor, mes, sum(qtd) qtd, sum(fat) fat from _pv_base group by 1, 2),
  pico as (select distinct on (setor) setor, mes, qtd, fat from setor_mes order by setor, qtd desc, mes),
  meses as (select generate_series(ini, alvo, interval '1 month')::date as mes),
  prod as (select distinct setor, id from _pv_base),
  grade as (
    select pr.setor, pr.id, m.mes, pc.mes as mes_pico,
           coalesce(bm.qtd, 0) qm, coalesce(bm.fat, 0) fm, coalesce(bp.qtd, 0) qp, coalesce(bp.fat, 0) fp
      from prod pr join pico pc on pc.setor = pr.setor cross join meses m
      left join _pv_base bm on bm.setor = pr.setor and bm.id = pr.id and bm.mes = m.mes
      left join _pv_base bp on bp.setor = pr.setor and bp.id = pr.id and bp.mes = pc.mes),
  linha as (
    select *, case when qp > 0 then fp / qp when qm > 0 then fm / qm else 0 end as unit from grade),
  calc as (
    select *, greatest(qp - qm, 0) * unit as perda, greatest(qm - qp, 0) * unit as ganho from linha),
  por_setor as (
    select setor, mes, min(mes_pico) mes_pico, sum(qp) qtd_pico, sum(qm) qtd_mes, sum(fp) fat_pico, sum(fm) fat_mes, sum(perda) perda, sum(ganho) ganho
      from calc group by setor, mes),
  escolhido as (
    select coalesce(sel, (select setor from por_setor where mes = alvo order by ganho - perda asc, setor limit 1)) as setor),
  top as (
    select c.id, c.qp, c.qm, c.unit, c.fp, c.fm, c.perda
      from calc c, escolhido e where c.setor = e.setor and c.mes = alvo and c.perda > 0
     order by c.perda desc, c.id limit 30),
  ev as (
    select h.idmercadoriavariacao i, h._idlocalestoque l, h.datahora t, h.qtdnovosaldo s
      from public.erp_mercadoria_estoque_historico h
     where h.idmercadoriavariacao in (select id from top) and h.sync_deleted_at is null
       and h.datahora < ((alvo + interval '1 month')::timestamp at time zone 'America/Belem')),
  pts as (
    select i, t from ev where t >= (alvo::timestamp at time zone 'America/Belem')
    union select id, (alvo::timestamp at time zone 'America/Belem') from top),
  saldo as (
    select pt.i, (select sum(x.s) from (select distinct on (e.l) e.s from ev e where e.i = pt.i and e.t <= pt.t order by e.l, e.t desc) x) as total
      from pts pt),
  ruptura as (select i, min(total) minimo, bool_or(total <= 0) zerou, count(total) pontos from saldo group by i),
  entradas as (
    select v.idmercadoriavariacao id, date_trunc('month', v.data)::date mes, sum(coalesce(v.qtdestoque, v.qtd)) qtd
      from public.vw_compra_item v
     where v.idmercadoriavariacao in (select id from top) and v.data >= ini and v.data < (alvo + interval '1 month')::date
     group by 1, 2)
  select jsonb_build_object(
    'mes', alvo, 'inicio', ini, 'setor', (select setor from escolhido),
    'setores', coalesce((select jsonb_agg(jsonb_build_object(
        'setor', s.setor, 'mes_pico', s.mes_pico, 'qtd_pico', round(s.qtd_pico, 3), 'qtd_mes', round(s.qtd_mes, 3),
        'fat_pico', round(s.fat_pico, 2), 'fat_mes', round(s.fat_mes, 2), 'perda', round(s.perda, 2), 'ganho', round(s.ganho, 2),
        'impacto', round(s.ganho - s.perda, 2), 'variacao', round(s.fat_mes - s.fat_pico, 2),
        'efeito_preco', round((s.fat_mes - s.fat_pico) - (s.ganho - s.perda), 2),
        'mercadoria', coalesce(l.mercadoria, true))
        order by (s.ganho - s.perda) asc, s.setor)
      from por_setor s left join public.cad_setor_comercial_lista l on l.nome = s.setor where s.mes = alvo), '[]'::jsonb),
    'serie', coalesce((select jsonb_agg(jsonb_build_object(
        'mes', s.mes, 'qtd', round(s.qtd_mes, 3), 'faturamento', round(s.fat_mes, 2), 'perda', round(s.perda, 2), 'ganho', round(s.ganho, 2),
        'impacto', round(s.ganho - s.perda, 2), 'efeito_preco', round((s.fat_mes - s.fat_pico) - (s.ganho - s.perda), 2),
        'variacao', round(s.fat_mes - s.fat_pico, 2), 'pico', s.mes = s.mes_pico) order by s.mes)
      from por_setor s, escolhido e where s.setor = e.setor), '[]'::jsonb),
    'produtos', coalesce((select jsonb_agg(jsonb_build_object(
        'id', t.id, 'nome', coalesce(n.nome, 'Item ' || t.id), 'qtd_pico', round(t.qp, 3), 'qtd_mes', round(t.qm, 3),
        'preco_pico', round(t.unit, 2), 'fat_pico', round(t.fp, 2), 'fat_mes', round(t.fm, 2), 'perda', round(t.perda, 2),
        'variacao', round(t.fm - t.fp, 2),
        'entradas_pico', coalesce((select x.qtd from entradas x, escolhido e2, por_setor ps where x.id = t.id and ps.setor = e2.setor and ps.mes = alvo and x.mes = ps.mes_pico), 0),
        'entradas_mes', coalesce((select x.qtd from entradas x where x.id = t.id and x.mes = alvo), 0),
        'estoque_atual', d.estoque_atual,
        'zerou_no_mes', r.zerou, 'saldo_minimo', r.minimo, 'com_historico', coalesce(r.pontos, 0) > 0)
        order by t.perda desc, t.id)
      from top t
      left join public.vw_variacao_nome n on n.idmercadoriavariacao = t.id
      left join public.vw_produto_ncm d on d.idmercadoriavariacao = t.id
      left join ruptura r on r.i = t.id), '[]'::jsonb)
  ) into res;
  return res;
end $$;

-- Conferência com o relatório do ERP: para cada mês de referência, o que o sistema soma na mesma janela
-- (data e hora de início e fim do relatório) e no mês inteiro.
create or replace function public.conferencia_erp() returns jsonb
language sql stable security definer set search_path = public, pg_catalog as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'mes', r.mes, 'inicio', r.inicio, 'fim', r.fim, 'arquivo', r.arquivo, 'fonte', r.fonte,
    'erp', jsonb_build_object('faturamento', r.faturamento, 'quantidade', r.quantidade, 'lucro', r.lucro),
    'sistema', (select jsonb_build_object('faturamento', round(coalesce(sum(v.valtotalliquido), 0), 2), 'quantidade', round(coalesce(sum(v.qtd), 0), 3), 'lucro', round(coalesce(sum(v.lucro_bruto), 0), 2), 'itens_sem_custo', count(*) filter (where v.custo_total is null))
                  from public.vw_venda_item v where v.datahora between r.inicio and r.fim),
    'mes_inteiro', (select jsonb_build_object('faturamento', round(coalesce(sum(v.valtotalliquido), 0), 2), 'quantidade', round(coalesce(sum(v.qtd), 0), 3), 'lucro', round(coalesce(sum(v.lucro_bruto), 0), 2))
                  from public.vw_venda_item v where v.data >= r.mes and v.data < (r.mes + interval '1 month')::date)
  ) order by r.mes), '[]'::jsonb)
  from public.ref_relatorio_erp r
$$;

revoke execute on function public.perda_volume(jsonb) from public;
revoke execute on function public.conferencia_erp() from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke execute on function public.perda_volume(jsonb) from anon';
    execute 'revoke execute on function public.conferencia_erp() from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke execute on function public.perda_volume(jsonb) from authenticated';
    execute 'revoke execute on function public.conferencia_erp() from authenticated';
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function public.perda_volume(jsonb) to service_role';
    execute 'grant execute on function public.conferencia_erp() to service_role';
    execute 'grant select, insert, update on public.cad_setor_comercial, public.cad_setor_comercial_lista, public.ref_relatorio_erp to service_role';
  end if;
end $$;

-- Produtos: lista com o setor comercial (view própria, para não mexer em vw_produto_ncm, que outras migrações recriam).
create or replace view public.vw_produto_lista with (security_invoker = true) as
select n.*, coalesce(scc.setor, 'Sem setor') as setor_comercial
  from public.vw_produto_ncm n
  left join public.cad_setor_comercial scc on scc.idmercadoriavariacao = n.idmercadoriavariacao;
